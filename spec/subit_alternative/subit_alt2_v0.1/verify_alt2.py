# formulas: ('ind',ax,a) ('obj',ax,a) ('not',f) ('and',f,g) ('box',ax,f) ('boxall',f) ('A',f) ('M',ax,b,f) ('X',f)
@lru_cache(maxsize=300000)
def ev(f, c, i):
    t = f[0]
    if t == 'ind': return c[f[1]] == f[2]
    if t == 'obj': return i[f[1]] == f[2]
    if t == 'not': return not ev(f[1], c, i)
    if t == 'and': return ev(f[1], c, i) and ev(f[2], c, i)
    if t == 'box':
        ax = f[1]
        return all(ev(f[2], c, i[:ax] + (v,) + i[ax+1:]) for v in range(4))
    if t == 'boxall': return all(ev(f[1], c, j) for j in S)
    if t == 'A': return ev(f[1], c, c)
    if t == 'M':
        ax, b = f[1], f[2]
        return ev(f[3], c[:ax] + (b,) + c[ax+1:], i)
    if t == 'X': return ev(f[1], c, (i[0], i[1], (i[2] + 1) % 4))
    raise ValueError(t)
def iff(f, g): return ('not', ('and', ('not', ('and', f, g)), ('not', ('and', ('not', f), ('not', g)))))
def imp(f, g): return ('not', ('and', f, ('not', g)))
def real_valid(f): return all(ev(f, c, c) for c in S)
def gen_valid(f): return all(ev(f, c, i) for c in S for i in S)
def fails_at(f): return sum(1 for c in S for i in S if not ev(f, c, i))

